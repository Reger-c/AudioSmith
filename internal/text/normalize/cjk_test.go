func TestChineseNumbers(t *testing.T) {
	cases := map[uint64]string{
		0: "零", 1: "一", 10: "十", 11: "十一", 15: "十五", 20: "二十", 100: "一百", 101: "一百零一",
		110: "一百一十", 1001: "一千零一", 1010: "一千零一十", 2000: "两千", 2222: "两千二百二十二",
		10000: "一万", 10001: "一万零一", 12345: "一万二千三百四十五", 20000: "两万", 100010: "十万零一十",
		1000000: "一百万", 100000000: "一亿", 100000001: "一亿零一", 120000000: "一亿二千万",
		1002003004: "十亿零二百万三千零四", 200000000: "两亿",
	}
	for n, want := range cases {
		if got := zhCardinal(n); got != want {
			t.Errorf("zhCardinal(%d) = %s, want %s", n, got, want)
		}
	}
}

